import os
from pathlib import Path

from concilia.demo.domain.dataset import DATASET_VERSION, ENGINE_CASES, Case, build_dataset
from tests.support.demo_engine import REFERENCE_CASES, EngineResults, engine_results

METRICS = Path(__file__).resolve().parents[4] / "docs" / "ENGINE_METRICS.md"
REGENERATE = "CONCILIA_WRITE_METRICS"

CASES = (
    (Case.EXACT, "R1", "One document in the description, exact amount"),
    (Case.SEVERAL_DOCUMENTS, "R2", "Several documents paid by one credit"),
    (Case.ROUNDING, "R3", "Referenced document with a small difference"),
    (Case.DETRACTION, "R3", "Referenced document with a detraction withheld"),
    (Case.SAME_CUSTOMER, "R4", "Same customer, several receivables, no reference"),
    (Case.PAID_IN_PARTS, "R5", "One receivable paid by several credits"),
    (Case.AMOUNT_AND_DATE, "R6", "Unique amount and date, no reference"),
    (Case.AMBIGUOUS, "—", "Several equally plausible receivables: left to people or the AI"),
    (Case.PARTIAL, "—", "Partial payment: reconciled by hand or from an AI suggestion"),
)


def _share(part: int, total: int) -> str:
    tenths = part * 1000 // total
    return f"{tenths // 10}.{tenths % 10} %"


def render(results: EngineResults) -> str:
    total = results.with_counterpart
    references = results.matched(REFERENCE_CASES)
    engine = results.matched(ENGINE_CASES)
    rows = "\n".join(
        f"| {case.value} | {rule} | {text} | {len(results.by_case.get(case, []))} "
        f"| {sum(results.by_case.get(case, []))} |"
        for case, rule, text in CASES
    )
    by_references = f"{references} ({_share(references, total)})"
    by_engine = f"{engine} ({_share(engine, total)})"
    return f"""# Engine metrics on the demo dataset

Demo dataset version {DATASET_VERSION}, generated by
`backend/tests/unit/demo/test_engine_metrics.py`.

The engine runs as the pure function it is, month by month, on the same credits and open
receivables the demo loads. Each proposal is compared with the receivables the generator says
each credit pays. Regenerate from `backend/` with
`{REGENERATE}=1 uv run pytest tests/unit/demo/test_engine_metrics.py`.

| Measure | Result | SPEC target |
| --- | --- | --- |
| Credits that pay receivables | {total} | — |
| Proposed correctly by rules 1 to 3 (references) | {by_references} | at least 70 % |
| Proposed correctly by rules 1 to 6 | {by_engine} | above 90 % with accepted AI suggestions |
| Wrong proposals | {len(results.wrong)} | 0 |

| Dataset case | Rule | What it is | Credits | Proposed correctly |
| --- | --- | --- | --- | --- |
{rows}

Credits that repeat a payment, pay nothing in the books, or are debits are left out: there is
nothing to match them with. Ambiguous credits and partial payments get no proposal on purpose:
R4 to R6 propose only when exactly one combination fits.
"""


def test_the_engine_metrics_document_is_current() -> None:
    expected = render(engine_results(build_dataset()))
    if os.environ.get(REGENERATE):
        METRICS.write_text(expected, encoding="utf-8", newline="\n")

    assert METRICS.read_text(encoding="utf-8") == expected, (
        f"run `{REGENERATE}=1 uv run pytest tests/unit/demo/test_engine_metrics.py`"
    )
